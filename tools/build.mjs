// Builds Thread Pulse from src/ with esbuild – run `npm run build` (or `python3 build.py`).
//   dist/ha-thread-pulse.js   dashboard card for HACS (ES module; loads thread-pulse-vis-network.js from its folder)
//   dist/thread-pulse.html    standalone page for an iframe/webpage card (needs thread-pulse-vis-network.js next to it)
// Not generated: dist/thread-pulse-vis-network.js is the graph library (vis-network 9.1.9, unmodified).
// The output is not minified, so the installed card stays readable.
import fs from "node:fs";
import path from "node:path";
import * as esbuild from "esbuild";

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const src = f => path.join(ROOT, "src", f), dist = f => path.join(ROOT, "dist", f);
const version = fs.readFileSync(src("version.js"), "utf8").match(/export const VERSION = "([^"]+)"/)[1];
const common = {
  bundle: true,
  write: false,
  target: "es2020",
  charset: "utf8",
  legalComments: "inline",
  loader: { ".css": "text", ".html": "text" },
  logLevel: "warning",
};

const card = await esbuild.build({ ...common, entryPoints: [src("card.js")], format: "esm" });
const banner = `// Thread Pulse ${version} – generated by tools/build.mjs from src/, do not edit. MIT License. https://github.com/riticulus/ha-thread-pulse\n`;
fs.mkdirSync(dist(""), { recursive: true });
fs.writeFileSync(dist("ha-thread-pulse.js"), banner + card.outputFiles[0].text);

const page = await esbuild.build({ ...common, entryPoints: [src("standalone.js")], format: "iife" });
const code = page.outputFiles[0].text;
if (/<\/script/i.test(code)) throw new Error("the page bundle must not contain </script>");
const html = fs.readFileSync(src("standalone.html"), "utf8").replace("/*VERSION*/", version).replace("/*BUNDLE*/", () => code.trimEnd());
fs.writeFileSync(dist("thread-pulse.html"), html);

if (!fs.existsSync(dist("thread-pulse-vis-network.js"))) throw new Error("dist/thread-pulse-vis-network.js (graph library) is missing");
console.log(`built ${version}: dist/thread-pulse.html, dist/ha-thread-pulse.js`);
