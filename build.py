#!/usr/bin/env python3
"""Build Thread Pulse from src/: the standalone page and the HACS dashboard card.

  python3 build.py

The core is assembled from the files in src/ in the order of CORE below (no bundler, no dependencies):
  version.js                    top level
  i18n/<lang>.js                one file per language (TEXT_XX, optional NAMES_XX); build.py adds TEXT and LOCAL_NAMES
  styles.css, markup.html       become the constants TP_CSS and TP_HTML
  core.js                       start of createThreadPulse() and the state shared by all parts
  helpers.js … ambient.js       parts placed inside createThreadPulse() (one file per topic)
  start.js                      start-up and public API; build.py adds the closing brace
Lines starting with "//#" at the top of a file are notes for developers and are not copied.

Outputs (do not edit by hand):
  thread-pulse.html                 standalone page for an iframe/webpage card (+ thread-pulse-vis-network.js next to it)
  dist/ha-thread-pulse.js           dashboard card for HACS
  dist/thread-pulse-vis-network.js  graph library, loaded by the card when it is shown
"""
import re, shutil
from pathlib import Path

here = Path(__file__).parent
src = here / "src"
PARTS = ["helpers", "data", "graph", "live", "heat", "rooms", "panel", "hints", "search", "changes", "response", "battery", "sound", "demo", "ui", "ambient"]

def languages():
    """Language files in src/i18n/: English first, then alphabetical. Each defines TEXT_XX and optionally NAMES_XX."""
    codes = sorted(p.stem for p in (src / "i18n").glob("*.js"))
    assert "en" in codes, "src/i18n/en.js is required"
    return ["en"] + [c for c in codes if c != "en"]

def i18n_lines():
    out = ["// ---------- texts (one file per language in src/i18n/) ----------"]
    with_names = []
    for code in languages():
        part = lines(f"i18n/{code}.js")
        assert any(l.startswith(f"const TEXT_{code.upper()} = {{") for l in part), f"i18n/{code}.js must define TEXT_{code.upper()}"
        if any(l.startswith(f"const NAMES_{code.upper()} = ") for l in part): with_names.append(code)
        out += part
    out.append("const TEXT = { " + ", ".join(f"{c}: TEXT_{c.upper()}" for c in languages()) + " };")
    out.append("const LOCAL_NAMES = { " + ", ".join(f"{c}: NAMES_{c.upper()}" for c in with_names) + " };")
    return out

def lines(name):
    text = (src / name).read_text(encoding="utf-8")
    assert text.endswith("\n"), f"{name} must end with a newline"
    out = text[:-1].split("\n")
    while out and out[0].startswith("//#"): out.pop(0)       # developer notes
    return out

core = "\n".join(
    lines("version.js")
    + ["const TP_CSS = `"] + lines("styles.css") + ["`;"]
    + ["const TP_HTML = `"] + lines("markup.html") + ["`;"]
    + i18n_lines()
    + lines("core.js")
    + [l for p in PARTS for l in lines(p + ".js")]
    + lines("start.js")
    + ["}", ""])
for marker in ("`", "${"):
    for name in ("styles.css", "markup.html"):
        assert marker not in "\n".join(lines(name)), f"{name} must not contain {marker!r}"

version = re.search(r'const VERSION = "([^"]+)"', core).group(1)
banner = f"// Thread Pulse {version} – generated by build.py from src/, do not edit. MIT License. https://github.com/riticulus/ha-thread-pulse\n"

page = (src / "standalone.html").read_text(encoding="utf-8")
page = page.replace("/*VERSION*/", version).replace("/*CORE*/", core.strip())
(here / "thread-pulse.html").write_text(page, encoding="utf-8")

(here / "dist").mkdir(exist_ok=True)
card = banner + core + (src / "card.js").read_text(encoding="utf-8")
(here / "dist/ha-thread-pulse.js").write_text(card, encoding="utf-8")
shutil.copyfile(here / "thread-pulse-vis-network.js", here / "dist/thread-pulse-vis-network.js")
print(f"built {version}: thread-pulse.html, dist/ha-thread-pulse.js, dist/thread-pulse-vis-network.js")
